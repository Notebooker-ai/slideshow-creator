"""Render trusted Remotion templates with data-only model output."""

from __future__ import annotations

import asyncio
import base64
import json
from pathlib import Path

from open_notebook_creator_sdk import CreationError, CreationFile

SOURCE_NAME = "slideshow.json"
_RENDER_LIMIT = asyncio.Semaphore(1)


def source_file() -> CreationFile:
    return CreationFile(
        filename=SOURCE_NAME,
        path=SOURCE_NAME,
        content_type="application/json",
        role="source",
        label="Slide source",
    )


async def _render_remotion(
    output_dir: Path, deck: dict
) -> tuple[list, list, list, list]:
    slides = []
    for raw in deck["slides"]:
        slide = dict(raw)
        if slide.get("svg_path"):
            path = (output_dir / slide["svg_path"]).resolve()
            if output_dir.resolve() not in path.parents:
                raise ValueError("Slide asset escapes output directory")
            # SVGs are generated by the trusted AntV sidecar, never model HTML.
            mime = "image/png" if path.suffix == ".png" else "image/svg+xml"
            slide["visual"] = (
                f"data:{mime};base64," + base64.b64encode(path.read_bytes()).decode()
            )
        slides.append(slide)
    script = Path(__file__).parent / "sidecar" / "remotion-render.mjs"
    proc = await asyncio.create_subprocess_exec(
        "node",
        str(script),
        stdin=asyncio.subprocess.PIPE,
        stdout=asyncio.subprocess.PIPE,
        stderr=asyncio.subprocess.PIPE,
    )
    try:
        out, err = await asyncio.wait_for(
            proc.communicate(
                json.dumps(
                    {**deck, "slides": slides, "outputDir": str(output_dir.resolve())}
                ).encode()
            ),
            timeout=900,
        )
    except TimeoutError:
        proc.kill()
        await proc.wait()
        raise RuntimeError("Remotion rendering timed out") from None
    if proc.returncode:
        raise RuntimeError(
            "Remotion rendering failed: " + err.decode(errors="replace")[-1500:]
        )
    review = json.loads(out.decode().rsplit("NOTEBOOKER_RESULT:", 1)[-1])
    files = [
        CreationFile(
            filename="slideshow.html",
            path="slideshow.html",
            content_type="text/html",
            label="Slideshow",
        ),
        CreationFile(
            filename="slideshow.mp4",
            path="slideshow.mp4",
            content_type="video/mp4",
            label="Video",
        ),
    ]
    warnings = list(review["overflow"])
    errors = [CreationError(phase="layout", message=issue) for issue in warnings]
    return files, warnings, errors, ["html", "mp4"]


async def render_remotion(
    output_dir: Path, deck: dict
) -> tuple[list, list, list, list]:
    """Keep a worker's video jobs from starting competing Chromium render farms."""
    async with _RENDER_LIMIT:
        return await _render_remotion(output_dir, deck)
